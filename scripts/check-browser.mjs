import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const { chromium } = await import(process.env.PLAYWRIGHT_PATH ? process.env.PLAYWRIGHT_PATH + "/index.mjs" : "playwright");
const browser = await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
const page = await browser.newPage({viewport:{width:1440,height:1000},baseURL:process.env.DESK_URL || "http://localhost:3000"});
const errors=[];
page.on("pageerror",error=>errors.push(error.message));
page.on("dialog", dialog=>void dialog.accept(dialog.type()==="prompt" ? "Test correction" : undefined));
async function login(id,password){
  await page.getByLabel("User ID",{exact:true}).fill(id);
  await page.getByLabel("Password",{exact:true}).fill(password);
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await page.getByRole("button",{name:"Sign out",exact:true}).waitFor();
}
try {
  await page.goto(process.env.DESK_URL || "http://localhost:3000");
  await login("advisor01","AdvisorDemo!2026");
  assert.equal(await page.locator(".sd-invoice").count(),3);
  assert.doesNotMatch(await page.locator("main").innerText(),/DEMO-260|Asha Nair/);
  assert.match(await page.locator(".sd-ledger-footer").innerText(),/96,938/);
  for (const [file,type] of [["ATA545.pdf","Counter sales"],["ACA1145.pdf","Accessories · non-TGA"],["INA2600101.pdf","Insurance claim"]]) {
    assert.match(await page.locator("main").innerText(),new RegExp(type));
    const response=await page.request.get("/api/demo/reference-bills?file="+encodeURIComponent(file));
    assert.equal(response.status(),200);
    assert.match(response.headers()["content-type"],/application\/pdf/);
    assert.deepEqual(await response.body(),readFileSync(file));
  }
  assert.equal((await page.request.get("/api/demo/reference-bills?file=..%2F.env.local")).status(),404);
  await page.getByRole("button",{name:"Upload & my bills",exact:true}).click();
  await page.getByRole("button",{name:"Upload bills",exact:true}).click();
  await page.locator('input[type="file"]').setInputFiles("TXA24-23030.pdf");
  await page.getByRole("button",{name:"Upload & read all",exact:true}).click();
  await page.locator(".sd-review-card").waitFor();
  assert.match(await page.locator(".sd-review-card").innerText(),/12,759/);
  assert.match(await page.locator(".sd-review-card").innerText(),/TXA24-23030/);
  await page.getByRole("button",{name:"Submit all"}).click();
  await page.getByText("0 ready · 0 failed · 0 / 10 PDFs",{exact:true}).waitFor();
  await page.getByRole("button",{name:"Close upload dialog",exact:true}).click();
  await page.getByRole("button",{name:"TXA24-23030",exact:true}).waitFor();
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await login("cashier01","CashierDemo!2026");
  await page.getByRole("button",{name:"Overview",exact:true}).click();
  assert.equal(await page.locator("nav button").count(), 2);
  assert.equal(await page.getByRole("button", {name: /Incoming bills|Unpaid bills/}).count(), 0);
  await page.getByRole("button",{name:"TXA24-23030",exact:true}).click();
  await page.getByRole("button",{name:"View original PDF"}).click();
  await page.getByTitle("Original bill PDF").waitFor();
  assert.equal(await page.getByRole("button", {name: "Approve bill", exact: true}).count(), 0);
  await page.getByRole("button",{name:/Mark as paid/}).waitFor();
  assert.equal(await page.locator("dialog input").count(),0,"Financial details must not be manually entered");
  await page.getByRole("button",{name:/Mark as paid/}).click();
  await page.getByText("Bill marked as paid and moved to Archive.", {exact:true}).waitFor();
  assert.equal(await page.getByRole("button", {name:"TXA24-23030",exact:true}).count(), 0);
  await page.getByRole("button", {name: /^Archive/}).click();
  await page.getByRole("button", {name:"TXA24-23030",exact:true}).click();
  await page.getByText("Full bill collected",{exact:false}).waitFor();
  assert.doesNotMatch(await page.locator("dialog").innerText(),/Part paid|Remaining|Method not stated/);
  await page.getByRole("heading",{name:"This customer’s bills"}).waitFor();
  await page.getByRole("button",{name:"Close bill details"}).click();
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await login("admin01","AdminDemo!2026");
  await page.getByRole("button",{name:"Overview",exact:true}).click();
  await page.locator(".sd-metric").filter({hasText:"Collected in full"}).click();
  await page.getByRole("button",{name:"TXA24-23030",exact:true}).click();
  await page.getByRole("button",{name:"Reverse entry",exact:true}).click();
  await page.getByText("Test correction",{exact:true}).first().waitFor();
  await page.getByRole("button",{name:"Close bill details"}).click();
  await page.getByRole("button",{name:/Bill archive/}).click();
  await page.getByRole("button",{name:"ACA/26-27/1145",exact:true}).click();
  assert.match(await page.locator(".sd-related").innerText(),/1 bill/);
  assert.match(await page.locator(".sd-related").innerText(),/40,752/);
  assert.doesNotMatch(await page.locator("dialog").innerText(),/Part paid|Remaining|₹5,000/);
  await page.getByRole("button",{name:"View original PDF"}).click();
  await page.getByTitle("Original bill PDF").waitFor();
  assert.match(await page.getByTitle("Original bill PDF").getAttribute("src"),/^blob:.*#page=1$/);
  assert.match(await page.locator(".sd-details").innerText(),/ACA1145\.pdf/);
  await page.screenshot({path:"/tmp/desk-reference-bill.png",fullPage:true});
  await page.getByRole("button",{name:"Close bill details"}).click();
  await page.getByRole("button",{name:"Staff accounts",exact:true}).click();
  await page.getByLabel("Full name",{exact:true}).fill("New advisor");
  await page.getByLabel("User ID",{exact:true}).fill("advisor02");
  await page.getByRole("button",{name:"Create account",exact:true}).click();
  await page.getByText("Share privately; shown for this session only.").waitFor();
  const temporary=(await page.locator(".sd-alert code").innerText()).split(" · ")[1];
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await login("advisor02",temporary);
  await page.getByRole("heading",{name:"Set your own password."}).waitFor();
  await page.getByLabel("New password",{exact:true}).fill("NewAdvisor!2026");
  await page.getByRole("button",{name:"Save password",exact:true}).click();
  await page.getByRole("heading",{name:"The bill archive."}).waitFor();
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await login("admin01","AdminDemo!2026");
  await page.reload();
  await page.getByRole("button",{name:"Refresh",exact:true}).waitFor();
  assert.equal(await page.locator(".sd-invoice").count(),4,"Refresh does not duplicate imports or remove other uploads");
  const state=await page.evaluate(()=>JSON.parse(localStorage.getItem("service-desk-finance-demo-v1")));
  assert.equal(state.payments.length,2,"Import refresh preserves collection and reversal history");
  await page.screenshot({path:"/tmp/desk-final-admin.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:"/tmp/desk-mobile.png",fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,"Page must fit mobile width");
  assert.deepEqual(errors,[]);
  console.log("Browser checks passed: upload, extracted amount, PDF preview, one-step payment and archive, admin drill-down, reversal, staff creation, first-login password change and mobile layout.");
} finally { await browser.close(); }
